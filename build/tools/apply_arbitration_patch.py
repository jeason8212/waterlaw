def main():
    dry = "--dry" in sys.argv
    touched = 0
    for fn in FILES:
        path = os.path.join(PROJ, "corpus", fn)
        rows = list(csv.DictReader(io.open(path, encoding="utf-8-sig")))
        fields = list(rows[0].keys())
        changed = []
        for r in rows:
            qid = r["query_id"]
            if qid not in U:
                continue
            for k, v in U[qid].items():
                assert k in fields, "%s 字段不存在: %s" % (qid, k)
                if r[k] != v:
                    r[k] = v
                    changed.append((qid, k))
            touched += 1
        print("%s: 命中 %d 行，改动 %d 个字段" %
              (fn, sum(1 for r in rows if r["query_id"] in U), len(changed)))
        if dry:
            continue
        bak = path + "." + STAMP
        if not os.path.exists(bak):
            shutil.copy2(path, bak)
        with io.open(path, "w", encoding="utf-8-sig", newline="") as f:
            w = csv.DictWriter(f, fieldnames=fields)
            w.writeheader()
            w.writerows(rows)
    print("总命中 %d 行%s" % (touched, "（dry run，未写入）" if dry else "，已写入"))


if __name__ == "__main__":
    main()
